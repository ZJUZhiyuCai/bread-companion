import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const bytes = await readFile(resolve(root, 'public/companion/hello-warm-bestie.mp3'));
const hash = createHash('sha256').update(bytes).digest('hex');
const output = `// Generated by node scripts/embed-call-greeting.mjs --write; do not edit audio bytes.\n// Source SHA-256: ${hash}\nconst recording = '${bytes.toString('base64')}';\n\n/** Fixed synthetic opening, loaded with the app; never contains a conversation. */\nexport function embeddedCallGreeting(): Blob {\n  return new Blob([Uint8Array.from(atob(recording), char => char.charCodeAt(0))], { type: 'audio/mpeg' });\n}\n`;
const target = resolve(root, 'domain/call-greeting-audio.ts');
if (process.argv.includes('--write')) await writeFile(target, output);
else if (await readFile(target, 'utf8') !== output) throw new Error('Embedded greeting is stale; run with --write.');
console.log(`Greeting: ${bytes.length} bytes, SHA-256 ${hash}`);
