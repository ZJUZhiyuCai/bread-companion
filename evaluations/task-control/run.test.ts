// Explicitly opt-in. Runs a bounded synthetic workflow through the actual controller.
import 'fake-indexeddb/auto';
import { it, expect } from 'vitest';
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { BreadController } from '@/services/bread-controller';
import { PROMPT_VERSION } from '@/prompts/agent';
import { validateCandidate } from '@/domain/evidence';
import { listSaved } from '@/services/card-store';
import type { TurnRequest } from '@/domain/types';

it('records a real synthetic core-task workflow without claiming user research', async () => {
  const base = new URL(process.env.BREAD_TASK_APP ?? '');
  if (!['127.0.0.1','localhost'].includes(base.hostname)) throw new Error('Use an explicitly configured local real-service candidate');
  const caps = await (await fetch(new URL('/api/capabilities', base))).json();
  expect(caps.agent.mode).toBe('real');
  const rows: unknown[] = [];
  const report = { synthetic: true, testedAt: new Date().toISOString(), promptVersion: PROMPT_VERSION, promptSha256: createHash('sha256').update(readFileSync('prompts/agent.ts')).digest('hex'), service: caps.agent.label, method: 'Actual BreadController → local production API → configured real model, one sample per step. No physical microphone or real participants. Human reading required for semantic quality.', rows };
  const save = () => writeFileSync('evaluations/task-control/actual-results.json', JSON.stringify(report, null, 2)+'\n');
  const controller = () => new BreadController(async (url, init) => {
    const input: TurnRequest = JSON.parse(init!.body as string); const started = performance.now();
    const response = await fetch(new URL(String(url), base), init);
    const output = await response.clone().json();
    rows.push({ input, status: response.status, elapsedMs: Math.round(performance.now()-started), output }); save();
    return response;
  });
  const c = controller();
  await c.send('刚收到产品实习的拒信。我准备了三天，最后只收到一句不合适。今晚不想听建议。');
  expect(c.getSnapshot().state.mode).toBe('listen'); expect(c.getSnapshot().error).toBe('');
  c.addMaterial('面试官问：怎样评测会议纪要 Agent？我回答：收集二十段会议录音，让模型生成纪要，再由我逐条核对是否漏掉决定事项。当时没有解释通过标准。这是我的回忆，不知道拒绝的原因。');
  await c.send('现在我想复盘了');
  expect(c.getSnapshot().currentCard?.type).toBe('review');
  const first = c.getSnapshot();
  const generated = rows.at(-1) as {input: TurnRequest; output: import('@/domain/types').TurnCandidate};
  const exaggerated = structuredClone(generated.output);
  const grounded = exaggerated.findings.find(f => f.evidenceRefs.length > 0)!;
  grounded.kind = 'inference'; grounded.text = '这段回答证明你整体能力不足。';
  rows.push({event:'adversarial-valid-quote-overstated-conclusion', syntheticMutation:true, input:generated.input, candidate:exaggerated, structuralErrors:validateCandidate(exaggerated, generated.input), interpretation:'An existing exact quote does not prove the inference. This is a structural-validator boundary probe, not a model-generated response.'}); save();
  const rejected = first.state.findings.find(f => f.kind === 'inference') ?? first.state.findings.find(f => f.kind === 'practice_suggestion');
  expect(rejected).toBeDefined();
  c.rejectFinding(rejected!.id);
  await c.assist('review', '不要把这一段当成我的整体能力；换个具体切口。');
  expect(c.getSnapshot().error).toBe('');
  expect(c.getSnapshot().state.rejectedFindings?.[0].text).toBe(rejected!.text);
  const source = c.getSnapshot().state.sources.find(s => s.text.startsWith('面试官问：'))!;
  c.correctSource(source.id, source.text.replace('二十段', '十段'));
  expect(c.getSnapshot().currentCard?.validity).toBe('stale');
  await c.assist('review'); expect(c.getSnapshot().error).toBe('');
  await c.assist('practice'); expect(c.getSnapshot().state.selectedQuestion).not.toBe('');
  await c.send('我会让两个人独立标出会议里的决定事项，比较纪要是否遗漏。现在还没做过这个实验，所以我没有通过率可报告。');
  expect(c.getSnapshot().error).toBe('');
  const card = c.getSnapshot().currentCard!;
  c.editCard(card.title, card.sections.map((s,i) => i ? s : {...s, text: s.text+' 我补写的计划：明天先试两段。'}));
  c.confirmCard(); await c.saveCard();
  const archive = (await listSaved()).find(s => s.caseId === c.getSnapshot().state.caseId)!;
  expect(archive.cards.some(card => card.sections.some(s => s.userEdited))).toBe(true);
  rows.push({event:'user-edit-and-explicit-save', archive});
  c.end(); rows.push({event:'end', lifecycle:c.getSnapshot().state.lifecycle, rawSources:c.getSnapshot().state.sources.length, corrections:c.getSnapshot().state.rejectedFindings?.length}); save(); c.dispose();
  const template = controller();
  template.addMaterial('感谢应聘。综合考虑，本次暂不合适，祝求职顺利。');
  await template.send('可以帮我看看刚才那段回答吗？');
  expect(template.getSnapshot().error).toBe('');
  await template.send('我现在不想复盘了');
  expect(template.getSnapshot().state.mode).toBe('listen');
  expect(template.getSnapshot().error).toBe(''); template.end(); template.dispose(); save();
});
